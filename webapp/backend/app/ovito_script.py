"""Build a genuine OVITO Python script from the settings of the OVITO page.

The OVITO worker executes exactly this text (with the import line swapped for a cached pipeline), and the page shows
the same text, so every image and number can be reproduced by running the script with OVITO (pip install ovito, or
OVITO Pro). Every user value is inserted as a Python literal (repr of a validated number, bool or string); nothing
from the request is ever inserted as code. OVITO expressions (selection, compute property) are OVITO's own
expression language, passed as string literals and evaluated by OVITO, not by Python.
"""
import re

GRADIENTS = ["Rainbow", "Jet", "Hot", "Grayscale", "BlueWhiteRed", "Viridis", "Magma", "CyclicRainbow"]
VIEWS = ["Top", "Bottom", "Front", "Back", "Left", "Right", "Ortho", "Perspective"]
ALIGN = {
    "top-left": "AlignTop | QtCore.Qt.AlignmentFlag.AlignLeft", "top": "AlignTop | QtCore.Qt.AlignmentFlag.AlignHCenter",
    "top-right": "AlignTop | QtCore.Qt.AlignmentFlag.AlignRight", "left": "AlignVCenter | QtCore.Qt.AlignmentFlag.AlignLeft",
    "right": "AlignVCenter | QtCore.Qt.AlignmentFlag.AlignRight", "bottom-left": "AlignBottom | QtCore.Qt.AlignmentFlag.AlignLeft",
    "bottom": "AlignBottom | QtCore.Qt.AlignmentFlag.AlignHCenter", "bottom-right": "AlignBottom | QtCore.Qt.AlignmentFlag.AlignRight",
}
DXA_LATTICES = ["CubicDiamond", "HexagonalDiamond", "FCC", "BCC", "HCP"]
MODIFIERS = {   # type -> label shown on the page (OVITO's own modifier names)
    "select_type": "Select type", "expression_selection": "Expression selection", "invert_selection": "Invert selection",
    "clear_selection": "Clear selection", "delete_selected": "Delete selected", "slice": "Slice",
    "displacements": "Displacement vectors", "coordination": "Coordination analysis", "identify_diamond": "Identify diamond structure",
    "cna": "Common neighbor analysis", "dxa": "Dislocation analysis (DXA)", "compute_property": "Compute property",
    "color_coding": "Color coding", "assign_color": "Assign color",
}
PROPERTY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_ .\[\]]{0,80}$")


def _num(v, name, lo=None, hi=None):
    try:
        x = float(v)
    except (TypeError, ValueError):
        raise ValueError(f"{name}: number expected")
    if x != x or x in (float("inf"), float("-inf")):
        raise ValueError(f"{name}: finite number expected")
    if lo is not None and x < lo or hi is not None and x > hi:
        raise ValueError(f"{name}: must be within {lo} … {hi}")
    return x


def _int(v, name, lo=None, hi=None):
    x = _num(v, name, lo, hi)
    if x != int(x):
        raise ValueError(f"{name}: integer expected")
    return int(x)


def _str(v, name, maxlen=300):
    if not isinstance(v, str) or len(v) > maxlen:
        raise ValueError(f"{name}: text of at most {maxlen} characters expected")
    return v


def _prop(v, name):
    v = _str(v, name, 80)
    if not PROPERTY_RE.match(v):
        raise ValueError(f"{name}: not a valid property name")
    return v


def _rgb(h, name):
    if not isinstance(h, str) or not re.match(r"^#[0-9a-fA-F]{6}$", h):
        raise ValueError(f"{name}: colour #rrggbb expected")
    return tuple(round(int(h[i:i + 2], 16) / 255, 4) for i in (1, 3, 5))


def _choice(v, options, name):
    if v not in options:
        raise ValueError(f"{name}: one of {', '.join(map(str, options))} expected")
    return v


def _align(v, name):
    return "QtCore.Qt.AlignmentFlag." + ALIGN[_choice(v, list(ALIGN), name)]


def build(spec, image_path="image.png", cached=False):
    """Return the OVITO script for `spec`. cached=True: worker variant reusing an already loaded file source."""
    src = spec.get("source") or {}
    path = _str(src.get("import_path"), "source", 1000)
    multi = bool(src.get("multiple_frames"))
    frame = _int(spec.get("frame", 0), "frame", 0)
    L = ["# Generated by NanoCut (OVITO page). Runs with the OVITO Python module: pip install ovito",
         "from ovito.io import import_file",
         "from ovito.modifiers import *",
         "from ovito.vis import *",
         "from ovito.qt_compat import QtCore",
         ""]
    if cached:
        L.append(f"pipeline = cached_pipeline({path!r}, multiple_frames={multi!r})")
        L.append("pipeline.modifiers.clear()")
    else:
        L.append(f"pipeline = import_file({path!r}{', multiple_frames=True' if multi else ''})")
    L.append(f"FRAME = {frame!r}")
    L.append("")

    # particle types (colour, radius) and the simulation cell, set by a Python function modifier
    styles = {}
    for tid, st in (spec.get("types") or {}).items():
        t = _int(tid, "type id", 0, 10 ** 6)
        styles[t] = (_rgb(st.get("color", "#cccccc"), f"type {t} colour"), _num(st.get("radius", 0.5), f"type {t} radius", 0.01, 50))
    show_cell = bool(spec.get("cell", False))
    L.append(f"TYPE_STYLE = {styles!r}    # type id -> (colour RGB 0..1, radius Å)")
    L.append("def particle_types_and_cell(frame, data):")
    L.append("    types = data.particles_.particle_types_")
    L.append("    for tid, (color, radius) in TYPE_STYLE.items():")
    L.append("        t = types.type_by_id_(tid) if types.type_by_id(tid) is not None else None")
    L.append("        if t is not None:")
    L.append("            t.color, t.radius = color, radius")
    L.append(f"    data.cell_.vis.enabled = {show_cell!r}")
    L.append("pipeline.modifiers.append(particle_types_and_cell)")
    L.append("")

    legend_var = None
    for k, m in enumerate(spec.get("modifiers") or []):
        if not m.get("enabled", True):
            continue
        t = _choice(m.get("type"), list(MODIFIERS), "modifier")
        v = f"m{k}"
        if t == "select_type":
            types = sorted({_int(x, "type", 0) for x in m.get("types", [])})
            L.append(f"{v} = SelectTypeModifier(property='Particle Type', types={set(types)!r})" if types else f"{v} = SelectTypeModifier(property='Particle Type', types=set())")
        elif t == "expression_selection":
            L.append(f"{v} = ExpressionSelectionModifier(expression={_str(m.get('expression', ''), 'expression')!r})")
        elif t == "invert_selection":
            L.append(f"{v} = InvertSelectionModifier()")
        elif t == "clear_selection":
            L.append(f"{v} = ClearSelectionModifier()")
        elif t == "delete_selected":
            L.append(f"{v} = DeleteSelectedModifier()")
        elif t == "slice":
            n = tuple(_num(x, "slice normal") for x in (m.get("normal") or [0, 0, 1])[:3])
            L.append(f"{v} = SliceModifier(normal={n!r}, distance={_num(m.get('distance', 0), 'slice distance')!r}, "
                     f"slab_width={_num(m.get('slab_width', 0), 'slab width', 0)!r}, inverse={bool(m.get('inverse'))!r}, select={bool(m.get('select'))!r})")
        elif t == "displacements":
            L.append(f"{v} = CalculateDisplacementsModifier(reference_frame={_int(m.get('reference_frame', 0), 'reference frame', 0)!r}, "
                     f"minimum_image_convention={bool(m.get('minimum_image', True))!r})")
        elif t == "coordination":
            L.append(f"{v} = CoordinationAnalysisModifier(cutoff={_num(m.get('cutoff', 2.6), 'cutoff', 0.1, 20)!r}, number_of_bins=200)")
        elif t == "identify_diamond":
            L.append(f"{v} = IdentifyDiamondModifier()")
        elif t == "cna":
            L.append(f"{v} = CommonNeighborAnalysisModifier()")
        elif t == "dxa":
            lat = _choice(m.get("lattice", "CubicDiamond"), DXA_LATTICES, "DXA lattice")
            L.append(f"{v} = DislocationAnalysisModifier(input_crystal_structure=DislocationAnalysisModifier.Lattice.{lat})")
        elif t == "compute_property":
            exprs = [_str(e, "expression") for e in (m.get("expressions") or [""])][:9]
            L.append(f"{v} = ComputePropertyModifier(output_property={_prop(m.get('output_property', 'My property'), 'output property')!r}, "
                     f"expressions={exprs!r}, only_selected={bool(m.get('only_selected'))!r})")
        elif t == "color_coding":
            g = _choice(m.get("gradient", "Rainbow"), GRADIENTS, "gradient")
            args = f"property={_prop(m.get('property', 'Position.Z'), 'colour property')!r}, gradient=ColorCodingModifier.{g}(), only_selected={bool(m.get('only_selected'))!r}"
            if m.get("start") is not None and m.get("end") is not None:
                args += f", auto_adjust_range=False, start_value={_num(m['start'], 'start value')!r}, end_value={_num(m['end'], 'end value')!r}"
            L.append(f"{v} = ColorCodingModifier({args})")
            legend_var = v
        elif t == "assign_color":
            L.append(f"{v} = AssignColorModifier(color={_rgb(m.get('color', '#35b6e0'), 'assign colour')!r})")
        L.append(f"pipeline.modifiers.append({v})")
    L.append("")
    L.append("data = pipeline.compute(FRAME)")
    L.append("for name, value in data.attributes.items():")
    L.append("    print(name, '=', value)")
    L.append("")

    view, rnd, ov = spec.get("view") or {}, spec.get("render") or {}, spec.get("overlays") or {}
    w, h = _int(rnd.get("w", 1600), "width", 64, 8000), _int(rnd.get("h", 1000), "height", 64, 8000)
    vt = _choice(view.get("type", "Top"), VIEWS, "view")
    L.append("pipeline.add_to_scene()")
    L.append(f"vp = Viewport(type=Viewport.Type.{vt})")
    if vt in ("Ortho", "Perspective") and view.get("camera_dir"):
        d = tuple(_num(x, "camera direction") for x in view["camera_dir"][:3])
        L.append(f"vp.camera_dir = {d!r}")
    L.append(f"vp.zoom_all(size=({w}, {h}))")
    zoom = _num(view.get("zoom", 1.0), "zoom", 0.05, 100)
    if zoom != 1.0:
        L.append(f"vp.fov = vp.fov / {zoom!r}    # zoom factor")
    if rnd.get("renderer", "opengl") == "tachyon":
        L.append(f"renderer = TachyonRenderer(antialiasing_samples={_int(rnd.get('aa', 12), 'antialiasing', 1, 64)!r}, "
                 f"ambient_occlusion={bool(rnd.get('ao', True))!r}, shadows={bool(rnd.get('shadows', False))!r})")
    else:
        L.append(f"renderer = OpenGLRenderer(antialiasing_level={_int(rnd.get('aa_gl', 3), 'antialiasing level', 1, 6)!r})")

    lg = ov.get("legend") or {}
    if lg.get("enabled") and legend_var:
        orient = "Vertical" if lg.get("orientation", "vertical") == "vertical" else "Horizontal"
        L.append(f"vp.overlays.append(ColorLegendOverlay(modifier={legend_var}, alignment={_align(lg.get('align', 'right'), 'legend position')}, "
                 f"orientation=QtCore.Qt.Orientation.{orient}, title={_str(lg.get('title', ''), 'legend title', 80)!r}, "
                 f"format_string={_str(lg.get('format', '%.2f Å'), 'legend format', 40)!r}, font_size={_num(lg.get('font_size', 0.1), 'legend text size', 0.01, 1)!r}, "
                 f"legend_size={_num(lg.get('size', 0.3), 'legend size', 0.05, 2)!r}, text_color={_rgb(lg.get('color', '#000000'), 'legend text colour')!r}, "
                 f"offset_x={_num(lg.get('ox', 0), 'legend offset x', -1, 1)!r}, offset_y={_num(lg.get('oy', 0), 'legend offset y', -1, 1)!r}))")
    tr = ov.get("tripod") or {}
    if tr.get("enabled"):
        L.append(f"vp.overlays.append(CoordinateTripodOverlay(alignment={_align(tr.get('align', 'bottom-left'), 'tripod position')}, "
                 f"size={_num(tr.get('size', 0.07), 'tripod size', 0.01, 1)!r}, offset_x={_num(tr.get('ox', 0), 'tripod offset x', -1, 1)!r}, "
                 f"offset_y={_num(tr.get('oy', 0), 'tripod offset y', -1, 1)!r}))")
    for i, lab in enumerate((ov.get("labels") or [])[:12]):
        if not lab.get("text"):
            continue
        L.append(f"vp.overlays.append(TextLabelOverlay(text={_str(lab['text'], 'label text', 200)!r}, alignment={_align(lab.get('align', 'top-left'), 'label position')}, "
                 f"font_size={_num(lab.get('font_size', 0.06), 'label size', 0.01, 1)!r}, text_color={_rgb(lab.get('color', '#000000'), 'label colour')!r}, "
                 f"offset_x={_num(lab.get('ox', 0), 'label offset x', -1, 1)!r}, offset_y={_num(lab.get('oy', 0), 'label offset y', -1, 1)!r}))")
    bg = _rgb(rnd.get("bg", "#ffffff"), "background")
    L.append(f"vp.render_image(size=({w}, {h}), filename={str(image_path)!r}, background={bg!r}, alpha={bool(rnd.get('alpha'))!r}, "
             f"frame=FRAME, renderer=renderer)")
    return "\n".join(L) + "\n"
